package com.example.data.local

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import com.example.data.AudioMeetingAnalysis
import com.example.data.ExtractedActionItem
import com.example.data.MeetingSession
import org.json.JSONArray
import org.json.JSONObject

/**
 * Room Entity storing Gemini-generated Executive Summaries (خلاصه اجرایی)
 * of meeting discussions and decisions immediately after audio recording finishes.
 */
@Entity(
    tableName = "executive_summaries",
    indices = [Index(value = ["sessionId"])]
)
data class ExecutiveSummaryEntity(
    @PrimaryKey(autoGenerate = true)
    val id: Int = 0,
    val sessionId: String,
    val sessionTitle: String,
    val sessionDate: String,
    val audioFilePath: String,
    val audioFileName: String,
    val audioDurationSec: Long,
    val executiveSummary: String,
    val keyDecisionsJson: String,
    val actionItemsJson: String,
    val fullTranscription: String,
    val isAutoGeneratedOnStop: Boolean = true,
    val createdAt: Long = System.currentTimeMillis()
) {
    fun getKeyDecisionsList(): List<String> {
        if (keyDecisionsJson.isBlank()) return emptyList()
        return try {
            val arr = JSONArray(keyDecisionsJson)
            buildList {
                for (i in 0 until arr.length()) {
                    val item = arr.optString(i, "").trim()
                    if (item.isNotBlank()) add(item)
                }
            }
        } catch (e: Exception) {
            emptyList()
        }
    }

    fun getActionItemsList(): List<ExtractedActionItem> {
        if (actionItemsJson.isBlank()) return emptyList()
        return try {
            val arr = JSONArray(actionItemsJson)
            buildList {
                for (i in 0 until arr.length()) {
                    val obj = arr.optJSONObject(i) ?: continue
                    add(
                        ExtractedActionItem(
                            id = obj.optString("id", "ACT-$i"),
                            title = obj.optString("title", ""),
                            assignee = obj.optString("assignee", "دبیر جلسه"),
                            deadline = obj.optString("deadline", "فوری / جاری"),
                            priority = obj.optString("priority", "فوری"),
                            isAddedToNotes = obj.optBoolean("isAddedToNotes", false)
                        )
                    )
                }
            }
        } catch (e: Exception) {
            emptyList()
        }
    }

    fun toAudioMeetingAnalysis(): AudioMeetingAnalysis {
        return AudioMeetingAnalysis(
            fullTranscription = fullTranscription,
            executiveSummary = executiveSummary,
            keyDecisions = getKeyDecisionsList(),
            actionItems = getActionItemsList(),
            audioDurationSec = audioDurationSec,
            audioFileName = audioFileName,
            timestamp = createdAt
        )
    }

    companion object {
        fun fromAudioAnalysis(
            session: MeetingSession,
            analysis: AudioMeetingAnalysis,
            audioFilePath: String = session.audioFilePath.orEmpty(),
            isAutoGeneratedOnStop: Boolean = true
        ): ExecutiveSummaryEntity {
            val decisionsArr = JSONArray().apply {
                analysis.keyDecisions.forEach { put(it) }
            }
            val actionsArr = JSONArray().apply {
                analysis.actionItems.forEach { item ->
                    put(
                        JSONObject().apply {
                            put("id", item.id)
                            put("title", item.title)
                            put("assignee", item.assignee)
                            put("deadline", item.deadline)
                            put("priority", item.priority)
                            put("isAddedToNotes", item.isAddedToNotes)
                        }
                    )
                }
            }

            return ExecutiveSummaryEntity(
                sessionId = session.id,
                sessionTitle = session.title.ifBlank { "جلسه راهبردی سازمانی (${session.id})" },
                sessionDate = session.date,
                audioFilePath = audioFilePath,
                audioFileName = analysis.audioFileName.ifBlank {
                    audioFilePath.substringAfterLast('/', "meeting_audio.m4a")
                },
                audioDurationSec = if (analysis.audioDurationSec > 0) analysis.audioDurationSec else session.audioDurationSec,
                executiveSummary = analysis.executiveSummary,
                keyDecisionsJson = decisionsArr.toString(),
                actionItemsJson = actionsArr.toString(),
                fullTranscription = analysis.fullTranscription,
                isAutoGeneratedOnStop = isAutoGeneratedOnStop,
                createdAt = analysis.timestamp
            )
        }
    }
}
