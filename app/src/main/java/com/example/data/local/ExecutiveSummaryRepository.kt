package com.example.data.local

import com.example.data.AudioMeetingAnalysis
import com.example.data.MeetingSession
import kotlinx.coroutines.flow.Flow

/**
 * Repository managing Room persistence of Gemini-generated post-recording
 * Executive Summaries (خلاصه اجرایی مباحث و تصمیمات جلسه).
 */
class ExecutiveSummaryRepository(
    private val summaryDao: ExecutiveSummaryDao,
    private val minutesSearchRepository: MinutesSearchRepository? = null
) {

    val allSummariesFlow: Flow<List<ExecutiveSummaryEntity>> =
        summaryDao.observeAllExecutiveSummaries()

    fun observeSummariesForSession(sessionId: String): Flow<List<ExecutiveSummaryEntity>> =
        summaryDao.observeSummariesForSession(sessionId)

    fun observeLatestSummaryForSession(sessionId: String): Flow<ExecutiveSummaryEntity?> =
        summaryDao.observeLatestSummaryForSession(sessionId)

    suspend fun getLatestSummaryForSessionOnce(sessionId: String): ExecutiveSummaryEntity? =
        summaryDao.getLatestSummaryForSessionOnce(sessionId)

    suspend fun getSummariesForSessionOnce(sessionId: String): List<ExecutiveSummaryEntity> =
        summaryDao.getSummariesForSessionOnce(sessionId)

    suspend fun getAllSummariesOnce(): List<ExecutiveSummaryEntity> =
        summaryDao.getAllSummariesOnce()

    /**
     * Persists a newly generated [AudioMeetingAnalysis] executive summary into the
     * Room `executive_summaries` table and synchronizes the session's `meeting_minutes` FTS record.
     */
    suspend fun saveExecutiveSummary(
        session: MeetingSession,
        analysis: AudioMeetingAnalysis,
        audioFilePath: String = session.audioFilePath.orEmpty(),
        isAutoGeneratedOnStop: Boolean = true
    ): ExecutiveSummaryEntity {
        val entity = ExecutiveSummaryEntity.fromAudioAnalysis(
            session = session,
            analysis = analysis,
            audioFilePath = audioFilePath,
            isAutoGeneratedOnStop = isAutoGeneratedOnStop
        )
        val rowId = summaryDao.insertExecutiveSummary(entity)
        val persisted = entity.copy(id = rowId.toInt())

        // Also synchronize with the Room meeting_minutes FTS table
        val updatedSession = session.copy(
            latestAudioAnalysis = analysis,
            aiSummary = analysis.executiveSummary.ifBlank { session.aiSummary }
        )
        minutesSearchRepository?.upsertSessionMinutes(updatedSession)

        return persisted
    }

    suspend fun deleteSummaryById(id: Int) {
        summaryDao.deleteSummaryById(id)
    }

    suspend fun deleteSummariesForSession(sessionId: String) {
        summaryDao.deleteSummariesForSession(sessionId)
    }
}
